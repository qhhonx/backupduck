#!/usr/bin/env python3
"""Fail when native page code adds literal colors or text sizes outside the token system.

Colors come from the generated tokens (DuckRole, DuckBrand, duck_role_*, ...)
and text uses semantic styles (DuckTextStyle, Dynamic Type text styles,
TextAppearance.BackupDuck.*). See design/constitution.md.

Existing violations are recorded per file and rule in design/literal-baseline.json.
The check fails when a count rises above the baseline, and also when it falls,
so the baseline always matches the code; run with --update-baseline after
removing violations. A documented exception is written next to the code that
needs it as a comment containing `design-exception: <reason>` on the same line
or the line above.
"""
import argparse
import json
import re
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASELINE = ROOT / 'design/literal-baseline.json'
TOKENS = json.loads((ROOT / 'design/foundations/tokens.json').read_text())

SWIFT_ROOTS = ('apps/ios/BackupDuck', 'apps/macos/BackupDuck', 'apps/apple/Shared')
ANDROID_CODE = 'apps/android/app/src/main/java'
ANDROID_RES = 'apps/android/app/src/main/res'

# Whole files that legitimately define literals, with the reason.
ALLOWED_FILES = {
    'apps/apple/Shared/DuckTokens.swift': 'Generated token definitions',
    f'{ANDROID_RES}/values/duck_colors.xml': 'Generated legacy palette',
    f'{ANDROID_RES}/values-night/duck_colors.xml': 'Generated legacy palette',
    f'{ANDROID_RES}/values/duck_scheme.xml': 'Generated Material 3 scheme',
    f'{ANDROID_RES}/values-night/duck_scheme.xml': 'Generated Material 3 scheme',
    f'{ANDROID_RES}/values/duck_theme.xml': 'Generated theme overlay and text appearances',
    f'{ANDROID_RES}/values/duck_dimens.xml': 'Generated spacing, radius and motion',
    f'{ANDROID_RES}/values/icon_colors.xml': 'Adaptive launcher icon background, part of the brand mark',
}
ALLOWED_DIRECTORIES = ('mipmap',)  # Launcher icon assets.

HUES = (r'red|orange|yellow|green|mint|teal|cyan|blue|indigo|purple|pink|brown|gray|grey|white|black|'
        r'darkGray|lightGray|magenta')
SYSTEM_HUES = r'system(?:Red|Orange|Yellow|Green|Mint|Teal|Cyan|Blue|Indigo|Purple|Pink|Brown|Gray\d?)'

RULES = {
    'swift': [
        ('color', 'color initializer',
         re.compile(r'\b(?:Color|UIColor|NSColor|CGColor)\(\s*(?:\.sRGB|\.displayP3|\.linearSRGB|red|hue|white|gray|'
                    r'srgbRed|calibratedRed|calibratedWhite|calibratedHue|deviceRed|deviceWhite|displayP3Red|genericGrayGamma2_2Gray)\b')),
        ('color', 'color literal or asset color',
         re.compile(r'#colorLiteral|\b(?:Color|UIColor|NSColor)\(\s*(?:named:\s*)?"')),
        ('color', 'named system color',
         re.compile(rf'\b(?:Color|UIColor|NSColor)\.(?:{HUES}|{SYSTEM_HUES})\b')),
        ('color', 'named color shorthand',
         re.compile(rf'(?:[(,?=]|\bcolor:|[^\w\s.]:)\s*\.(?:{HUES}|{SYSTEM_HUES})\b(?!\s*[(:])')),
        ('text-size', 'fixed font size',
         re.compile(r'\.system\(\s*size:|\bFont\.custom\(|\.custom\(\s*"|'
                    r'\.(?:systemFont|boldSystemFont|italicSystemFont|monospacedDigitSystemFont|monospacedSystemFont)\(\s*ofSize:|'
                    r'\b(?:UIFont|NSFont)\(\s*name:')),
    ],
    'kotlin': [
        ('color', 'color constructor', re.compile(r'\bColor\.(?:parseColor|rgb|argb|valueOf)\(')),
        ('color', 'ARGB literal', re.compile(r'\b0[xX][fF]{2}[0-9a-fA-F]{6}\b')),
        ('color', 'named framework color',
         re.compile(r'\bColor\.(?:WHITE|BLACK|RED|GREEN|BLUE|GRAY|DKGRAY|LTGRAY|YELLOW|CYAN|MAGENTA)\b')),
        ('text-size', 'fixed text size',
         re.compile(r'\btextSize\s*=|\bsetTextSize\(|COMPLEX_UNIT_SP|\bduckText\((?:[^(),]|\([^()]*\))*,\s*\d+\b')),
    ],
    'xml': [
        ('color', 'hex color', re.compile(r'(?<![\w&])#[0-9A-Fa-f]{3,8}\b')),
        ('text-size', 'fixed text size', re.compile(r'textSize"?\s*(?:=\s*"|>)\s*[\d.]+(?:sp|dp|px)')),
    ],
}
EXCEPTION = re.compile(r'design-exception:\s*\S')
ILLUSTRATION_MARKER = 'Generated by scripts/export-illustrations.py'


def scanned_files():
    for root in SWIFT_ROOTS:
        for file in sorted((ROOT / root).rglob('*.swift')):
            yield file, 'swift'
    for file in sorted((ROOT / ANDROID_CODE).rglob('*')):
        if file.suffix in ('.kt', '.java'):
            yield file, 'kotlin'
    for file in sorted((ROOT / ANDROID_RES).rglob('*.xml')):
        # Brand illustrations use the fixed illustration palette (constitution § Color).
        if ILLUSTRATION_MARKER in file.read_text(errors='ignore')[:300]:
            continue
        if not file.parent.name.startswith(ALLOWED_DIRECTORIES):
            yield file, 'xml'


def strip_comment(line, language):
    """Drop trailing line comments so prose about colors is not counted."""
    if language == 'xml':
        return re.sub(r'<!--.*?-->', '', line)
    return re.sub(r'(?<!:)//.*$', '', line)


def tinted_vector_source(source):
    """Mask only path color literals replaced by an explicit vector tint."""
    try:
        root = ET.fromstring(source)
    except ET.ParseError:
        return source
    tint = (root.get('{http://schemas.android.com/apk/res/android}tint') or '').strip()
    if root.tag != 'vector' or not tint or tint == '@null':
        return source
    attributes = re.compile(r'\bandroid:(?:fillColor|strokeColor)\s*=\s*([\'\"])(.*?)\1', re.DOTALL)

    def mask(match):
        # Preserve line breaks and offsets for findings and exception comments.
        if not re.fullmatch(r'\s*#[0-9A-Fa-f]{3,8}\s*', match.group(2)):
            return match.group()
        return re.sub(r'#[0-9A-Fa-f]{3,8}\b', lambda color: ' ' * len(color.group()), match.group())

    return attributes.sub(mask, source)


def scan():
    findings = defaultdict(list)
    for file, language in scanned_files():
        path = file.relative_to(ROOT).as_posix()
        if path in ALLOWED_FILES:
            continue
        source = file.read_text(encoding='utf-8')
        lines = source.splitlines()
        scan_lines = tinted_vector_source(source).splitlines() if language == 'xml' else lines
        for index, line in enumerate(lines):
            if EXCEPTION.search(line) or (index and EXCEPTION.search(lines[index - 1])):
                continue
            code = strip_comment(scan_lines[index], language)
            for kind, label, pattern in RULES[language]:
                for _ in pattern.finditer(code):
                    findings[(path, kind)].append((index + 1, label, line.strip()))
    return findings


def legacy_usage():
    """Count uses of the retired 0.3.0 palette names, for migration tracking."""
    names = list(TOKENS['legacy']['colors']['light'])
    snake = [re.sub(r'(?<!^)(?=[A-Z])', '_', n).lower() for n in names]
    swift = re.compile(r'\bDuckColors\.(?:' + '|'.join(names) + r')\b')
    android = re.compile(r'(?:R\.color\.|@color/)duck_(?:' + '|'.join(snake) + r')\b')
    count = 0
    for file, language in scanned_files():
        if file.relative_to(ROOT).as_posix() in ALLOWED_FILES:
            continue
        pattern = swift if language == 'swift' else android
        count += len(pattern.findall(file.read_text(encoding='utf-8')))
    return count


def counts(findings):
    table = defaultdict(dict)
    for (path, kind), items in sorted(findings.items()):
        table[path][kind] = len(items)
    return {path: table[path] for path in sorted(table)}


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--update-baseline', action='store_true', help='record current violations as the baseline')
    parser.add_argument('--report', action='store_true', help='list every current violation')
    args = parser.parse_args()
    findings = scan()
    current = counts(findings)
    total = {kind: sum(c.get(kind, 0) for c in current.values()) for kind in ('color', 'text-size')}
    if args.update_baseline:
        BASELINE.write_text(json.dumps({
            'note': 'Generated by scripts/check-design-literals.py --update-baseline. Existing literal colors and '
                    'text sizes in native page code; counts may only fall. Migrate pages to generated tokens and '
                    'semantic text styles instead of adding entries.',
            'totals': total,
            'files': current,
        }, indent=2) + '\n')
        print(f'Recorded {total["color"]} literal colors and {total["text-size"]} literal text sizes '
              f'in {len(current)} files.')
        return
    if args.report:
        for (path, kind), items in sorted(findings.items()):
            for line, label, text in items:
                print(f'{path}:{line}: {kind}: {label}: {text[:140]}')
    baseline = json.loads(BASELINE.read_text())['files'] if BASELINE.exists() else {}
    added, removed = [], []
    for path in sorted(set(current) | set(baseline)):
        for kind in ('color', 'text-size'):
            now, before = current.get(path, {}).get(kind, 0), baseline.get(path, {}).get(kind, 0)
            if now > before:
                added.append((path, kind, now, before))
            elif now < before:
                removed.append((path, kind, now, before))
    for path, kind, now, before in added:
        print(f'{path}: {now} literal {kind} uses, baseline allows {before}:', file=sys.stderr)
        for line, label, text in findings[(path, kind)]:
            print(f'  {path}:{line}: {label}: {text[:140]}', file=sys.stderr)
    for path, kind, now, before in removed:
        print(f'{path}: {now} literal {kind} uses, below baseline {before}.', file=sys.stderr)
    summary = (f'{total["color"]} literal colors and {total["text-size"]} literal text sizes in {len(current)} files; '
               f'{legacy_usage()} uses of legacy palette names.')
    if added:
        raise SystemExit('New literal colors or text sizes. Use generated tokens and semantic text styles, or add a '
                         '`design-exception: <reason>` comment next to the code. ' + summary)
    if removed:
        raise SystemExit('Baseline is stale; run python3 scripts/check-design-literals.py --update-baseline. ' + summary)
    print('Design literals within baseline: ' + summary)


if __name__ == '__main__':
    main()
