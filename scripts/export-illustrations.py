#!/usr/bin/env python3
"""Export the approved duck poses and step marks to each platform.

Sources: assets/illustrations/backupduck-poses-v3/svg (the poses) and the wing
outline in assets/illustrations/duck-master/duck-master.svg (the second step
mark). Outputs:

- apps/apple/Resources/Illustrations.xcassets: one vector image set per asset.
- apps/android/app/src/main/res/drawable: one VectorDrawable per asset.

Run after changing a source; `--check` fails when outputs are stale.
"""
import json
import math
import pathlib
import re
import sys
import xml.etree.ElementTree as ET

ROOT = pathlib.Path(__file__).resolve().parent.parent
POSES = ROOT / 'assets/illustrations/backupduck-poses-v3/svg'
MASTER = ROOT / 'assets/illustrations/duck-master/duck-master.svg'
APPLE = ROOT / 'apps/apple/Resources/Illustrations.xcassets'
ANDROID = ROOT / 'apps/android/app/src/main/res/drawable'
SVG = 'http://www.w3.org/2000/svg'
ANDROID_NS = 'http://schemas.android.com/apk/res/android'
NOTICE = 'Generated by scripts/export-illustrations.py. Do not edit.'

POSE_NAMES = {'01-welcome': 'welcome', '02-pairing': 'pairing', '03-empty': 'empty',
              '04-done': 'done', '05-waiting': 'waiting', '06-premium': 'premium'}
BRAND = {'yellow': '#FEC613', 'blue': '#1065E4', 'orange': '#FA7212'}


def marks():
    """Step marks as standalone SVGs: shapes only, numbers are drawn by the app."""
    wing = re.search(r'<path id="wing" d="([^"]+)"', MASTER.read_text()).group(1)
    return {
        'mark-circle': f'<svg xmlns="{SVG}" viewBox="0 0 100 100" width="100" height="100"><circle cx="50" cy="50" r="46" fill="{BRAND["yellow"]}"/></svg>',
        'mark-wing': f'<svg xmlns="{SVG}" viewBox="195 515 590 290" width="590" height="290"><path d="{wing}" fill="{BRAND["blue"]}"/></svg>',
        'mark-sparkle': f'<svg xmlns="{SVG}" viewBox="0 0 100 100" width="100" height="100"><path d="M50 2 Q58 42 98 50 Q58 58 50 98 Q42 58 2 50 Q42 42 50 2Z" fill="{BRAND["orange"]}"/></svg>',
    }


def sources():
    out = {f'duck-{name}': (POSES / f'{stem}.svg').read_text() for stem, name in POSE_NAMES.items()}
    out.update(marks())
    return out


def camel(name):
    return ''.join(part.capitalize() for part in name.split('-'))


# ---------- Apple ----------

def apple_files(name, svg):
    folder = f'{camel(name)}.imageset'
    contents = {'images': [{'filename': f'{name}.svg', 'idiom': 'universal'}],
                'info': {'author': 'xcode', 'version': 1},
                'properties': {'preserves-vector-representation': True, 'template-rendering-intent': 'original'}}
    return {f'{folder}/{name}.svg': svg, f'{folder}/Contents.json': json.dumps(contents, indent=2) + '\n'}


# ---------- Android ----------

def tag(el):
    return el.tag.split('}')[-1]


def num(value):
    text = f'{float(value):.3f}'.rstrip('0').rstrip('.')
    return '0' if text in ('-0', '') else text


def circle_path(cx, cy, r):
    return (f'M{num(cx - r)},{num(cy)}A{num(r)},{num(r)} 0 1,0 {num(cx + r)},{num(cy)}'
            f'A{num(r)},{num(r)} 0 1,0 {num(cx - r)},{num(cy)}Z')


def rect_path(x, y, w, h, rx):
    if rx <= 0:
        return f'M{num(x)},{num(y)}h{num(w)}v{num(h)}h{num(-w)}Z'
    rx = min(rx, w / 2, h / 2)
    return (f'M{num(x + rx)},{num(y)}H{num(x + w - rx)}A{num(rx)},{num(rx)} 0 0,1 {num(x + w)},{num(y + rx)}'
            f'V{num(y + h - rx)}A{num(rx)},{num(rx)} 0 0,1 {num(x + w - rx)},{num(y + h)}'
            f'H{num(x + rx)}A{num(rx)},{num(rx)} 0 0,1 {num(x)},{num(y + h - rx)}'
            f'V{num(y + rx)}A{num(rx)},{num(rx)} 0 0,1 {num(x + rx)},{num(y)}Z')


def group_attrs(transform):
    """One SVG transform list to VectorDrawable group attributes (scale, rotate, then translate)."""
    attrs = {}
    for op, args in re.findall(r'(\w+)\s*\(([^)]*)\)', transform or ''):
        v = [float(x) for x in re.split(r'[\s,]+', args.strip()) if x]
        if op == 'translate':
            attrs['translateX'] = num(v[0] + float(attrs.get('translateX', 0)))
            attrs['translateY'] = num((v[1] if len(v) > 1 else 0) + float(attrs.get('translateY', 0)))
        elif op == 'scale':
            if 'rotation' in attrs or 'translateX' in attrs:
                # "translate(...) scale(...)": SVG scales first, which is VectorDrawable's order too.
                pass
            attrs['scaleX'] = num(v[0])
            attrs['scaleY'] = num(v[1] if len(v) > 1 else v[0])
        elif op == 'rotate':
            if len(attrs):
                raise SystemExit(f'unsupported transform order: {transform}')
            attrs['rotation'] = num(v[0])
            if len(v) == 3:
                attrs['pivotX'], attrs['pivotY'] = num(v[1]), num(v[2])
        else:
            raise SystemExit(f'unsupported transform {op}')
    return attrs


def vector(svg_text):
    root = ET.fromstring(svg_text)
    vb = [float(x) for x in root.get('viewBox').split()]
    out = ET.Element('vector', {'xmlns:android': ANDROID_NS, 'android:width': '120dp',
                                'android:height': f'{num(120 * vb[3] / vb[2])}dp',
                                'android:viewportWidth': num(vb[2]), 'android:viewportHeight': num(vb[3])})
    parent = out
    if vb[0] or vb[1]:
        parent = ET.SubElement(out, 'group', {'android:translateX': num(-vb[0]), 'android:translateY': num(-vb[1])})

    def walk(el, into):
        for child in el:
            kind = tag(child)
            if kind == 'g':
                attrs = {f'android:{k}': v for k, v in group_attrs(child.get('transform')).items()}
                walk(child, ET.SubElement(into, 'group', attrs))
            elif kind in ('path', 'circle', 'rect'):
                if kind == 'path':
                    d = child.get('d')
                elif kind == 'circle':
                    d = circle_path(float(child.get('cx')), float(child.get('cy')), float(child.get('r')))
                else:
                    d = rect_path(float(child.get('x', 0)), float(child.get('y', 0)), float(child.get('width')),
                                  float(child.get('height')), float(child.get('rx', 0)))
                target = into
                if child.get('transform'):
                    target = ET.SubElement(into, 'group', {f'android:{k}': v for k, v in group_attrs(child.get('transform')).items()})
                attrs = {'android:pathData': d}
                fill = child.get('fill')
                if fill and fill != 'none':
                    attrs['android:fillColor'] = fill
                if child.get('stroke') and child.get('stroke') != 'none':
                    attrs['android:strokeColor'] = child.get('stroke')
                    attrs['android:strokeWidth'] = num(child.get('stroke-width', 1))
                    if child.get('stroke-linecap'):
                        attrs['android:strokeLineCap'] = child.get('stroke-linecap')
                    if child.get('stroke-linejoin'):
                        attrs['android:strokeLineJoin'] = child.get('stroke-linejoin')
                if 'android:fillColor' not in attrs and 'android:strokeColor' not in attrs:
                    attrs['android:fillColor'] = '#000000'
                ET.SubElement(target, 'path', attrs)
            elif kind in ('title', 'desc', 'defs'):
                continue
            else:
                raise SystemExit(f'unsupported element <{kind}>')

    walk(root, parent)
    ET.indent(out)
    return f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {NOTICE} -->\n' + ET.tostring(out, encoding='unicode') + '\n'


def outputs():
    files = {}
    for name, svg in sources().items():
        for path, text in apple_files(name, svg).items():
            files[APPLE / path] = text
        files[ANDROID / f'{name.replace("-", "_")}.xml'] = vector(svg)
    files[APPLE / 'Contents.json'] = json.dumps({'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n'
    return files


def main():
    check = '--check' in sys.argv
    stale = []
    for path, text in outputs().items():
        if check:
            if not path.exists() or path.read_text() != text:
                stale.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    if check:
        if stale:
            print('Stale illustration exports:\n' + '\n'.join(f'  {p.relative_to(ROOT)}' for p in stale))
            sys.exit(1)
        print('Illustration exports verified.')
    else:
        print('Exported illustrations for Apple and Android.')


if __name__ == '__main__':
    main()
