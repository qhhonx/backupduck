def android(outputs):
    for index, (theme, directory) in enumerate((('light', 'values'), ('dark', 'values-night'))):
        legacy = [f'<color name="duck_{snake(name)}">{value}</color>' for name, value in LEGACY[theme].items()]
        outputs[f'{ANDROID_RES}/{directory}/duck_colors.xml'] = xml(
            ['<!-- Legacy 0.3.0 palette; pages move to duck_role_* and duck_state_* colors. -->'] + legacy)
        scheme = [f'<color name="duck_m3_{snake(role)}">{values[index]}</color>' for role, values in SCHEME.items()]
        for name, parts in STATES.items():
            scheme += [f'<color name="duck_state_{snake(name)}">{parts["foreground"][theme]}</color>',
                       f'<color name="duck_state_{snake(name)}_container">{parts["container"][theme]}</color>',
                       f'<color name="duck_state_on_{snake(name)}_container">{parts["onContainer"][theme]}</color>']
        if theme == 'light':
            # Media colors are fixed and inherited unchanged by values-night.
            for name, spec in media_colors().items():
                alpha = round(spec.get('opacity', 1) * 255)
                scheme.append(f'<color name="duck_media_{snake(name)}">#{alpha:02X}{spec["value"].lstrip("#")}</color>')
            scheme += [f'<color name="duck_brand_{snake(name)}">{value}</color>' for name, value in PRIMARIES.items()]
            scheme += [f'<color name="duck_illustration_{snake(name)}">{value}</color>'
                       for name, value in ILLUSTRATION.items()]
            scheme += [f'<color name="duck_role_accent">@color/duck_m3_primary</color>']
            scheme += [f'<color name="duck_role_{snake(name)}">@color/duck_m3_{snake(spec["android"])}</color>'
                       for name, spec in NEUTRAL.items() if 'androidOpacity' not in spec]
        for name, spec in NEUTRAL.items():
            if 'androidOpacity' in spec:
                alpha = round(spec['androidOpacity'] * 255)
                foreground = SCHEME[spec['android']][index].lstrip('#')
                scheme.append(f'<color name="duck_role_{snake(name)}">#{alpha:02X}{foreground}</color>')
        outputs[f'{ANDROID_RES}/{directory}/duck_scheme.xml'] = xml(scheme)
    theme = ['<!-- Fixed Material 3 scheme seeded from wing blue. Wallpaper dynamic color is not used. -->',
             '<style name="ThemeOverlay.BackupDuck.Scheme" parent="">']
    theme += [f'    <item name="{attribute}">@color/duck_m3_{snake(role)}</item>'
              for role, attribute in ANDROID_ATTRIBUTES.items()]
    theme.append('</style>')
    for name, spec in TOKENS['text']['styles'].items():
        theme.append(f'<!-- {spec["meaning"]}. -->')
        parent = f'TextAppearance.Material3.{spec["android"]}'
        if spec.get('monospacedDigits'):
            theme += [f'<style name="TextAppearance.BackupDuck.{upper_first(name)}" parent="{parent}">',
                      '    <item name="android:fontFeatureSettings">tnum</item>', '</style>']
        else:
            theme.append(f'<style name="TextAppearance.BackupDuck.{upper_first(name)}" parent="{parent}" />')
    outputs[f'{ANDROID_RES}/values/duck_theme.xml'] = xml(theme)
    dimens = [f'<dimen name="duck_space_{snake(name)}">{value}dp</dimen>'
              for name, value in TOKENS['spacing'].items() if name != 'note']
    dimens += [f'<dimen name="duck_radius_{snake(name)}">{value}dp</dimen>' for name, value in TOKENS['radius'].items()]
    motion = TOKENS['motion']
    dimens += [f'<integer name="duck_motion_{snake(name)}_ms">{value}</integer>'
               for name, value in motion['durationsMs'].items()]
    dimens.append(f'<dimen name="duck_motion_enter_offset">{motion["enterOffset"]}dp</dimen>')
    outputs[f'{ANDROID_RES}/values/duck_dimens.xml'] = xml(dimens)
    x1, y1, x2, y2 = (f'{v:g}' for v in motion['standardCurve'])
    outputs[f'{ANDROID_RES}/interpolator/duck_standard.xml'] = (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f'<!-- {NOTICE} -->\n'
        '<pathInterpolator xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:controlX1="{x1}" android:controlY1="{y1}" android:controlX2="{x2}" android:controlY2="{y2}" />\n')


