def css_rule(selector, declarations):
    return selector + '{' + ';'.join(f'{name}:{value}' for name, value in declarations) + '}'


def web_colors(mode, high_contrast=False):
    appearance = mode + ('IncreasedContrast' if high_contrast else '')
    declarations = [('--duck-accent', ACCENT[appearance])]
    for name, parts in STATES.items():
        declarations += [(f'--duck-state-{kebab(name)}', parts['foreground'][appearance]),
                         (f'--duck-state-{kebab(name)}-container', parts['container'][appearance])]
    if high_contrast:
        return declarations
    declarations = [('color-scheme', mode)] + [(f'--duck-{kebab(n)}', v) for n, v in LEGACY[mode].items()] + declarations
    declarations += [(f'--duck-{kebab(name)}', spec['web'][mode]) for name, spec in NEUTRAL.items()]
    return declarations


def web():
    shared = [(f'--duck-brand-{kebab(name)}', value) for name, value in PRIMARIES.items()]
    shared += [(f'--duck-illustration-{kebab(name)}', value) for name, value in ILLUSTRATION.items()]
    for name, spec in media_colors().items():
        value = spec['value']
        if 'opacity' in spec:
            rgb = [int(value[i:i + 2], 16) for i in (1, 3, 5)]
            value = f'rgba({rgb[0]},{rgb[1]},{rgb[2]},{spec["opacity"]:g})'
        shared.append((f'--duck-media-{kebab(name)}', value))
    family = '-apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,sans-serif'
    shared.append(('--duck-font-family', family))
    for name, spec in TOKENS['text']['styles'].items():
        style = spec['web']
        shared.append((f'--duck-font-{kebab(name)}',
                       f'{style["weight"]} {style["size"]}px/{style["lineHeight"]}px {family}'))
        if spec.get('monospacedDigits'):
            shared.append((f'--duck-font-{kebab(name)}-numeric', 'tabular-nums'))
    shared += [(f'--duck-space-{kebab(name)}', f'{value}px') for name, value in TOKENS['spacing'].items() if name != 'note']
    shared += [(f'--duck-radius-{kebab(name)}', f'{value}px') for name, value in TOKENS['radius'].items()]
    motion = TOKENS['motion']
    shared += [(f'--duck-motion-{kebab(name)}', f'{value}ms') for name, value in motion['durationsMs'].items()]
    shared.append(('--duck-motion-enter-offset', f'{motion["enterOffset"]}px'))
    shared.append(('--duck-ease-standard', 'cubic-bezier(' + ','.join(f'{v:g}' for v in motion['standardCurve']) + ')'))
    dark_auto = ':root:not([data-theme="light"])'
    rules = [f'/* {NOTICE} */',
             css_rule(':root', web_colors('light') + shared),
             css_rule(':root[data-theme="dark"]', web_colors('dark')),
             '@media(prefers-color-scheme:dark){' + css_rule(dark_auto, web_colors('dark')) + '}',
             '@media(prefers-contrast:more){' + css_rule(':root', web_colors('light', True))
             + css_rule(':root[data-theme="dark"]', web_colors('dark', True)) + '}',
             '@media(prefers-contrast:more) and (prefers-color-scheme:dark){'
             + css_rule(dark_auto, web_colors('dark', True)) + '}']
    return '\n'.join(rules) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--check', action='store_true', help='verify generated files instead of writing them')
    args = parser.parse_args()
    problems = check_contrast()
    if problems:
        raise SystemExit('Design token contrast failures:\n  ' + '\n  '.join(problems))
    outputs = {'apps/apple/Shared/DuckTokens.swift': apple(), 'crates/native/src/dashboard/tokens.css': web()}
    android(outputs)
    stale = []
    for name, content in outputs.items():
        file = ROOT / name
        if args.check:
            if not file.exists() or file.read_text() != content:
                stale.append(name)
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(content)
    if stale:
        raise SystemExit('Stale design tokens; run scripts/export-design-tokens.py: ' + ', '.join(stale))
    print('Design tokens verified.' if args.check else 'Exported Apple, Android and browser design tokens.')


if __name__ == '__main__':
    main()
