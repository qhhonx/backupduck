#!/usr/bin/env python3
"""Generate Apple, Android and browser design tokens from design/backupduck-v1/tokens.json.

Outputs brand primaries, accent/neutral/state roles, fixed media overlays and
Apple selection, the illustration palette, semantic text styles, spacing, radius
and motion, plus the legacy
0.3.0 palette under its original names. `--check` fails when any generated file
is stale or a derived color misses its contrast floor.
"""
import argparse
import json
import re
from pathlib import Path

import design_color as color

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'design/backupduck-v1/tokens.json'
TOKENS = json.loads((ROOT / SOURCE).read_text())
NOTICE = f'Generated by scripts/export-design-tokens.py from {SOURCE}; do not edit.'
APPEARANCES = ('light', 'dark', 'lightIncreasedContrast', 'darkIncreasedContrast')
ANDROID_RES = 'apps/android/app/src/main/res'


def snake(name):
    return re.sub(r'(?<!^)(?=[A-Z])', '_', name).lower()


def kebab(name):
    return snake(name).replace('_', '-')


SWIFT_KEYWORDS = {'switch', 'case', 'default', 'repeat', 'return', 'in', 'is', 'as', 'do', 'if', 'else', 'for',
                  'while', 'break', 'continue', 'defer', 'guard', 'throw', 'where', 'static', 'self', 'let', 'var'}


def swift_name(name):
    return f'`{name}`' if name in SWIFT_KEYWORDS else name


def upper_first(name):
    return name[0].upper() + name[1:]


# Derived values ---------------------------------------------------------------

PRIMARIES = {name: spec['value'] for name, spec in TOKENS['brand']['primaries'].items()}


def tonal(source, tone_set):
    tones = dict(TOKENS['tones'][tone_set])
    limit = tones.pop('maxChroma', None)
    chroma = None if limit is None else min(limit, color.hct(source)[1])
    return {appearance: color.tone_of(source, tone, chroma) for appearance, tone in tones.items()}


ACCENT = tonal(PRIMARIES[TOKENS['accent']['seed']], 'accent')
STATES = {name: {part: tonal(spec['source'], part) for part in ('foreground', 'container', 'onContainer')}
          for name, spec in TOKENS['state'].items() if isinstance(spec, dict)}
ILLUSTRATION = {}
for name, spec in TOKENS['illustration']['colors'].items():
    if 'value' in spec:
        ILLUSTRATION[name] = spec['value']
    elif 'tone' in spec:
        ILLUSTRATION[name] = color.tone_of(PRIMARIES[spec['primary']], spec['tone'])
    else:
        ILLUSTRATION[name] = PRIMARIES[spec['primary']]
NEUTRAL = TOKENS['neutral']
LEGACY = TOKENS['legacy']['colors']


def android_scheme():
    android = TOKENS['android']
    seed_hue, seed_chroma, _ = color.hct(PRIMARIES[android['seed']])
    palettes = {}
    for name, spec in android['palettes'].items():
        hue = spec.get('hue', (seed_hue + spec.get('hueOffset', 0)) % 360)
        chroma = seed_chroma if spec['chroma'] == 'seed' else spec['chroma']
        palettes[name] = (hue, chroma)
    scheme = {}
    for role, (palette, light, dark) in android['roles'].items():
        hue, chroma = palettes[palette]
        scheme[role] = (color.from_hct(hue, chroma, light), color.from_hct(hue, chroma, dark))
    return scheme


SCHEME = android_scheme()


def check_contrast():
    """Fail generation when a derived foreground cannot be read on its surfaces."""
    problems = []

    def need(label, foreground, background, minimum):
        ratio = color.contrast(foreground, background)
        if ratio < minimum:
            problems.append(f'{label}: {foreground} on {background} is {ratio:.2f}:1, needs {minimum}:1')

    web_surfaces = {mode: [NEUTRAL[role]['web'][mode] for role in ('background', 'groupedSurface', 'elevatedSurface')]
                    for mode in ('light', 'dark')}
    for appearance in APPEARANCES:
        mode = 'dark' if appearance.startswith('dark') else 'light'
        minimum = 7 if appearance.endswith('IncreasedContrast') else 4.5
        for surface in web_surfaces[mode]:
            need(f'accent {appearance}', ACCENT[appearance], surface, minimum)
            for name, parts in STATES.items():
                need(f'{name} {appearance}', parts['foreground'][appearance], surface, 4.5)
        for name, parts in STATES.items():
            need(f'{name} on container {appearance}', parts['foreground'][appearance], parts['container'][appearance], 4.5)
            need(f'{name} onContainer {appearance}', parts['onContainer'][appearance], parts['container'][appearance], 4.5)
    for mode in ('light', 'dark'):
        for surface in web_surfaces[mode]:
            for role in ('primaryText', 'secondaryText'):
                need(f'web {role} {mode}', NEUTRAL[role]['web'][mode], surface, 4.5)
    for index, mode in enumerate(('light', 'dark')):
        for foreground, background in (('onPrimary', 'primary'), ('onSurface', 'surface'),
                                       ('onSurfaceVariant', 'surfaceContainerHigh'), ('primary', 'surfaceContainer'),
                                       ('onPrimaryContainer', 'primaryContainer'), ('onError', 'error')):
            need(f'android {foreground} {mode}', SCHEME[foreground][index], SCHEME[background][index], 4.5)
    return problems


# Apple ------------------------------------------------------------------------

def swift_hex(value):
    return '0x' + value.lstrip('#').upper()


def apple_adaptive(values):
    if len(values) == 2:
        return f'DuckPalette.adaptive(light: {swift_hex(values[0])}, dark: {swift_hex(values[1])})'
    light, dark, light_high, dark_high = (swift_hex(values[a]) for a in APPEARANCES)
    return (f'DuckPalette.adaptive(light: {light}, dark: {dark}, '
            f'lightIncreasedContrast: {light_high}, darkIncreasedContrast: {dark_high})')


def apple_neutral(name, platform):
    system = NEUTRAL[name][platform]
    if name == 'elevatedSurface' and platform == 'ios':
        return ('Color(uiColor: UIColor { traits in\n'
                '    UIColor.systemBackground.resolvedColor(with: traits.modifyingTraits { $0.userInterfaceLevel = .elevated })\n'
                '  })')
    return f'Color({"nsColor" if platform == "macos" else "uiColor"}: .{system})'


def media_colors():
    """Flatten named scrim opacities without introducing appearance variants."""
    colors = {}
    for name, spec in TOKENS['media'].items():
        if not isinstance(spec, dict):
            continue
        colors[name] = spec
        for opacity_name, opacity in spec.get('opacities', {}).items():
            colors[name + upper_first(opacity_name)] = dict(value=spec['value'], opacity=opacity,
                meaning=f"{spec['meaning']}; existing {opacity_name} opacity")
    return colors


def apple_media():
    lines = [f"/// {TOKENS['media']['note']}", 'enum DuckMedia {']
    for platform, native, suffix, label in [('macOS', 'NSColor', 'NSColor', 'nsColor'),
                                             ('iOS', 'UIColor', 'UIColor', 'uiColor')]:
        lines.append('  #if os(macOS)' if platform == 'macOS' else '  #else')
        for name, spec in media_colors().items():
            base = '.white' if spec['value'] == '#FFFFFF' else '.black'
            value = native + base
            if 'opacity' in spec:
                value += f".withAlphaComponent({spec['opacity']:g})"
            lines += [f"  /// {spec['meaning']}.", f'  static let {name}{suffix} = {value}',
                      f'  static let {name} = Color({label}: {name}{suffix})',
                      f'  static let {name}CGColor = {name}{suffix}.cgColor']
    lines += ['  #endif', '}', '', f"/// {TOKENS['selection']['note']}", 'enum DuckSelection {', '  #if os(macOS)']
    for name, spec in TOKENS['selection'].items():
        if not isinstance(spec, dict):
            continue
        lines += [f"  /// {spec['meaning']}.",
                  f"  static let {name}NSColor = NSColor.controlAccentColor.withAlphaComponent({spec['opacity']:g})",
                  f'  static let {name} = Color(nsColor: {name}NSColor)']
    lines.append('  #else')
    for name, spec in TOKENS['selection'].items():
        if not isinstance(spec, dict):
            continue
        lines += [f"  static let {name} = AnyShapeStyle(TintShapeStyle().opacity({spec['opacity']:g}))",
                  f"  static func {name}(tint: Color) -> Color {{ tint.opacity({spec['opacity']:g}) }}",
                  f"  static func {name}UIColor(tint: UIColor) -> UIColor {{ tint.withAlphaComponent({spec['opacity']:g}) }}"]
    lines += ['  #endif', '}', '']
    return lines


APPLE_WEIGHTS = {'regular': 'regular', 'medium': 'medium', 'semibold': 'semibold', 'bold': 'bold'}


def apple_text_styles():
    styles = TOKENS['text']['styles']
    lines = ['/// Semantic text styles mapped to Dynamic Type (design/constitution.md#typography-spacing-and-shape).',
             'enum DuckTextStyle: CaseIterable {']
    for name, spec in styles.items():
        lines.append(f'  /// {spec["meaning"]}.')
        lines.append(f'  case {name}')
    lines += ['', '  /// The SwiftUI font, which follows the user\'s text size.', '  var font: Font {', '    switch self {']
    for name, spec in styles.items():
        apple = spec['apple']
        font = f'.{apple["style"]}'
        if 'weight' in apple:
            font += f'.weight(.{APPLE_WEIGHTS[apple["weight"]]})'
        if spec.get('monospacedDigits'):
            font += '.monospacedDigit()'
        lines.append(f'    case .{name}: return {font}')
    lines += ['    }', '  }', '', '  var weight: PlatformFont.Weight {', '    switch self {']
    for name, spec in styles.items():
        lines.append(f'    case .{name}: return .{APPLE_WEIGHTS[spec["apple"].get("weight", "regular")]}')
    lines += ['    }', '  }', '', '  var monospacedDigits: Bool {', '    switch self {']
    for name, spec in styles.items():
        lines.append(f'    case .{name}: return {"true" if spec.get("monospacedDigits") else "false"}')
    lines += ['    }', '  }', '', '  var textStyle: PlatformFont.TextStyle {', '    switch self {']
    for name, spec in styles.items():
        lines.append(f'    case .{name}: return .{spec["apple"]["style"]}')
    lines += ['    }', '  }', '',
              '  /// The UIKit or AppKit font for the same style. UIKit fonts scale with Dynamic Type',
              '  /// when the view sets adjustsFontForContentSizeCategory.',
              '  var platformFont: PlatformFont {',
              '    #if os(macOS)',
              '    let size = NSFont.preferredFont(forTextStyle: textStyle).pointSize',
              '    return monospacedDigits ? .monospacedDigitSystemFont(ofSize: size, weight: weight) : .systemFont(ofSize: size, weight: weight)',
              '    #else',
              '    let size = UIFont.preferredFont(forTextStyle: textStyle, compatibleWith: UITraitCollection(preferredContentSizeCategory: .large)).pointSize',
              '    let base: UIFont = monospacedDigits ? .monospacedDigitSystemFont(ofSize: size, weight: weight) : .systemFont(ofSize: size, weight: weight)',
              '    return UIFontMetrics(forTextStyle: textStyle).scaledFont(for: base)',
              '    #endif',
              '  }',
              '}',
              '',
              'extension View {',
              '  /// Applies a semantic text style.',
              '  func duckTextStyle(_ style: DuckTextStyle) -> some View { font(style.font) }',
              '}']
    return lines


def apple_native_palette():
    """Cached dynamic native providers for HCT roles, without SwiftUI bridging."""
    return '''
extension DuckPalette {
  #if os(macOS)
  static func adaptiveNSColor(light: UInt32, dark: UInt32, lightIncreasedContrast: UInt32, darkIncreasedContrast: UInt32) -> NSColor {
    NSColor(name: nil) { appearance in
      let names: [NSAppearance.Name] = [.aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua]
      let value: UInt32
      switch appearance.bestMatch(from: names) {
      case .darkAqua: value = dark
      case .accessibilityHighContrastAqua: value = lightIncreasedContrast
      case .accessibilityHighContrastDarkAqua: value = darkIncreasedContrast
      default: value = light
      }
      let c = components(value)
      return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: 1)
    }
  }
  #else
  static func adaptiveUIColor(light: UInt32, dark: UInt32, lightIncreasedContrast: UInt32, darkIncreasedContrast: UInt32) -> UIColor {
    UIColor { traits in
      let high = traits.accessibilityContrast == .high
      let value = traits.userInterfaceStyle == .dark ? (high ? darkIncreasedContrast : dark) : (high ? lightIncreasedContrast : light)
      let c = components(value)
      return UIColor(red: c.0, green: c.1, blue: c.2, alpha: 1)
    }
  }
  #endif
}
'''.strip().splitlines()


def apple():
    lines = [f'// {NOTICE}', 'import SwiftUI', '#if os(macOS)', 'import AppKit', 'typealias PlatformFont = NSFont',
             '#else', 'import UIKit', 'typealias PlatformFont = UIFont', '#endif', '',
             '/// Fixed brand colors from the app icon, for illustration and brand marks only.',
             'enum DuckBrand {']
    for name, spec in TOKENS['brand']['primaries'].items():
        lines += [f'  /// {spec["use"]}.', f'  static let {name} = DuckPalette.fixed({swift_hex(spec["value"])})']
    lines += ['', '  /// Illustration palette. Never colors controls.', '  enum Illustration {']
    for name, value in ILLUSTRATION.items():
        lines.append(f'    static let {name} = DuckPalette.fixed({swift_hex(value)})')
    lines += ['  }', '}', '',
              '/// Semantic interface colors (design/constitution.md#color).',
              'enum DuckRole {',
              f'  /// {TOKENS["accent"]["meaning"]}. Used as the tint.',
              f'  static let accent = {apple_adaptive(ACCENT)}', '']
    lines.append('  #if os(macOS)')
    for name, spec in NEUTRAL.items():
        lines += [f'  /// {spec["meaning"]}.', f'  static let {name} = {apple_neutral(name, "macos")}']
    lines.append('  #else')
    for name, spec in NEUTRAL.items():
        lines += [f'  /// {spec["meaning"]}.', f'  static let {name} = {apple_neutral(name, "ios")}']
    lines.append('  #endif')
    for name, parts in STATES.items():
        lines += ['', f'  /// {TOKENS["state"][name]["meaning"]}. Pair with an icon or text.',
                  f'  static let {name} = {apple_adaptive(parts["foreground"])}',
                  f'  static let {name}Container = {apple_adaptive(parts["container"])}']
    # Native callers share dynamic colors without bridging SwiftUI per tile/frame.
    for platform, native in [('macos', 'NSColor'), ('ios', 'UIColor')]:
        lines.append('  #if os(macOS)' if platform == 'macos' else '  #else')
        for name in ['accent'] + list(NEUTRAL) + [part for name in STATES for part in (name, name + 'Container')]:
            if name in NEUTRAL and not (name == 'elevatedSurface' and platform == 'ios'):
                value = f'{native}.{NEUTRAL[name][platform]}'
            elif name == 'elevatedSurface' and platform == 'ios':
                value = ('UIColor { traits in UIColor.systemBackground.resolvedColor(with: '
                         'traits.modifyingTraits { $0.userInterfaceLevel = .elevated }) }')
            else:
                values = ACCENT if name == 'accent' else STATES[name[:-9] if name.endswith('Container') else name]['container' if name.endswith('Container') else 'foreground']
                arguments = ', '.join(f'{appearance}: {swift_hex(values[appearance])}' for appearance in APPEARANCES)
                value = f'DuckPalette.adaptive{native}({arguments})'
            lines.append(f'  static let {name}{native} = {value}')
    lines += ['  #endif']
    lines += ['}', '',
              f'/// {TOKENS["glyph"]["note"]}',
              'enum DuckGlyph {']
    for name, spec in TOKENS['glyph']['colors'].items():
        lines += ['  #if os(macOS)', f'  static let {name}NSColor = NSColor.{spec["apple"]}', f'  static let {name} = Color(nsColor: {name}NSColor)',
                  '  #else', f'  static let {name}UIColor = UIColor.{spec["apple"]}', f'  static let {name} = Color(uiColor: {name}UIColor)', '  #endif']
    lines += ['}', '']
    lines += apple_media()
    lines += apple_text_styles()
    lines += ['', '/// Spacing for custom-drawn surfaces. System controls keep their own metrics.', 'enum DuckSpacing {']
    for name, value in TOKENS['spacing'].items():
        if name != 'note':
            lines.append(f'  static let {name}: CGFloat = {value}')
    lines += ['}', '', 'enum DuckRadius {']
    for name, value in TOKENS['radius'].items():
        lines.append(f'  static let {name}: CGFloat = {value}')
    motion = TOKENS['motion']
    lines += ['}', '', '/// Durations in seconds; see design/backupduck-v1/motion.md.', 'enum DuckMotion {']
    for name, value in motion['durationsMs'].items():
        lines.append(f'  static let {swift_name(name)}: Double = {value / 1000:g}')
    curve = ', '.join(f'{v:g}' for v in motion['standardCurve'])
    lines += [f'  static let enterOffset: CGFloat = {motion["enterOffset"]}',
              f'  static func standard(duration: Double) -> Animation {{ .timingCurve({curve}, duration: duration) }}',
              '}', '',
              f'/// {TOKENS["legacy"]["note"]}',
              'enum DuckColors {']
    for name, light in LEGACY['light'].items():
        lines.append(f'  static let {name} = {apple_adaptive((light, LEGACY["dark"][name]))}')
    lines += ['}', '',
              'enum DuckPalette {',
              '  static func fixed(_ value: UInt32) -> Color {',
              '    let c = components(value)',
              '    return Color(.sRGB, red: c.0, green: c.1, blue: c.2, opacity: 1)',
              '  }',
              '',
              '  static func adaptive(light: UInt32, dark: UInt32) -> Color {',
              '    adaptive(light: light, dark: dark, lightIncreasedContrast: light, darkIncreasedContrast: dark)',
              '  }',
              '',
              '  static func adaptive(light: UInt32, dark: UInt32, lightIncreasedContrast: UInt32, darkIncreasedContrast: UInt32) -> Color {',
              '    #if os(macOS)',
              '    return Color(nsColor: NSColor(name: nil) { appearance in',
              '      let names: [NSAppearance.Name] = [.aqua, .darkAqua, .accessibilityHighContrastAqua, .accessibilityHighContrastDarkAqua]',
              '      let value: UInt32',
              '      switch appearance.bestMatch(from: names) {',
              '      case .darkAqua: value = dark',
              '      case .accessibilityHighContrastAqua: value = lightIncreasedContrast',
              '      case .accessibilityHighContrastDarkAqua: value = darkIncreasedContrast',
              '      default: value = light',
              '      }',
              '      let c = components(value)',
              '      return NSColor(srgbRed: c.0, green: c.1, blue: c.2, alpha: 1)',
              '    })',
              '    #else',
              '    return Color(uiColor: UIColor { traits in',
              '      let high = traits.accessibilityContrast == .high',
              '      let value = traits.userInterfaceStyle == .dark ? (high ? darkIncreasedContrast : dark) : (high ? lightIncreasedContrast : light)',
              '      let c = components(value)',
              '      return UIColor(red: c.0, green: c.1, blue: c.2, alpha: 1)',
              '    })',
              '    #endif',
              '  }',
              '',
              '  private static func components(_ value: UInt32) -> (CGFloat, CGFloat, CGFloat) {',
              '    (CGFloat((value >> 16) & 0xFF) / 255, CGFloat((value >> 8) & 0xFF) / 255, CGFloat(value & 0xFF) / 255)',
              '  }',
              '}']
    return '\n'.join(lines + [''] + apple_native_palette()) + '\n'


